'use strict';
const path = require('node:path');
const fs = require('node:fs');
const { spawnSync } = require('node:child_process');
const root = path.resolve(__dirname, '..');
const cache = path.join(root, '.cache');
process.env.ELECTRON_CACHE ||= path.join(cache, 'electron');
process.env.ELECTRON_BUILDER_CACHE ||= path.join(cache, 'builder');
process.env.CSC_IDENTITY_AUTO_DISCOVERY = 'false';
const web = spawnSync(process.execPath, [path.join(root, '..', 'web', 'verify.cjs')], { cwd: root, stdio: 'inherit' });
if (web.status !== 0) process.exit(web.status || 1);
require('./prepare.cjs');
const testFiles = fs.readdirSync(path.join(root, 'test')).filter(name => name.endsWith('.test.cjs')).map(name => path.join('test', name));
const tests = spawnSync(process.execPath, ['--test', ...testFiles], { cwd: root, stdio: 'inherit' });
if (tests.status !== 0) process.exit(tests.status || 1);
const desktop = spawnSync(process.execPath, [path.join(root, '..', 'web', 'verify.cjs'), '--desktop'], { cwd: root, stdio: 'inherit' });
if (desktop.status !== 0) process.exit(desktop.status || 1);
const cli = require.resolve('electron-builder/cli.js');
const args = [cli, '--win', '--x64', '--dir', '--publish', 'never'];
args.push('--config.electronDownload.cache=' + require('./electron-cache.cjs').prepareElectronCache(root));
const result = spawnSync(process.execPath, args, { cwd: root, env: process.env, stdio: 'inherit' });
if (result.status !== 0) process.exit(result.status || 1);
